km = float(input("Quantos km percorreu o carro :"))
dias = int(input("Quantos dias foi alugado :"))
preço = 40 * km
day = 60 * dias
total = preço + day
print("O carro percorreu",km,"km e o preço a pagar é",preço,"MT")
print("E para os dias foram",dias,"que corresponde a",day,"MT")
print("O total a pagar é dê",total,"MT")